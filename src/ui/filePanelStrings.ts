type FilePanelStringKey = keyof typeof strings.en;

export function filePanelText(key: FilePanelStringKey, values: Record<string, string | number> = {}): string {
  const language = getLanguage() === 'en' ? 'en' : 'pl';
  return strings[language][key].replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? ''));
}
